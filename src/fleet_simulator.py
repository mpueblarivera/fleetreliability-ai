"""Stochastic Fleet Degradation Simulator and Operational CBM Runner.

Simulates a mixed-criticality industrial fleet (``L``, ``M``, ``H``) evolving
through bounded Random Walk / Wiener degradation processes across operating
shifts, streams JSON telemetry to the FastAPI inference service using only
Python stdlib HTTP primitives (``urllib.request`` / ``urllib.error``), tracks
per-shift operational semaphores and work orders (OTs), and compares cumulative
operational costs using ``src.montecarlo`` parameters.

Note on MLOps Validation Separation:
    Latent physical failure events generated by this simulator are used
    **exclusively** for operational and economic policy accounting. Statistical
    generalization metrics (PR-AUC, ROC-AUC, F2, Brier) are never computed on
    synthetic simulator trajectories.
"""

