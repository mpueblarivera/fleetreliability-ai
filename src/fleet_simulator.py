# Physical bounds aligned strictly with src.predict.TelemetryPayload
AIR_TEMP_MIN: float = 250.0
AIR_TEMP_MAX: float = 350.0
PROCESS_TEMP_MIN: float = 250.0
PROCESS_TEMP_MAX: float = 380.0
THERMAL_COHERENCE_MARGIN: float = 5.0
RPM_MIN: float = 500.0
RPM_MAX: float = 3500.0
TORQUE_MIN: float = 0.0
TORQUE_MAX: float = 200.0
TOOL_WEAR_MIN: float = 0.0
TOOL_WEAR_MAX: float = 400.0

MACHINE_TYPES: tuple[str, ...] = ("L", "M", "H")
OPERATIONAL_STATUSES: tuple[str, ...] = (
    "NORMAL",
    "INSPECTION_REQUIRED",
    "CRITICAL_INTERVENTION",
)


@dataclass
class MachineState:
    """Mutable physical state of a single simulated industrial asset."""

    machine_id: str
    machine_type: str
    air_temperature_k: float
    process_temperature_k: float
    rotational_speed_rpm: float
    torque_nm: float
    tool_wear_min: float
    degradation_rate: float


@dataclass(frozen=True)
class TelemetryStep:
    """Single deterministic telemetry observation and operational ground truth."""

    step: int
    shift: int
    hour_in_shift: int
    payload: dict[str, Any]
    latent_failure: int


def _validate_positive_int(value: int, name: str) -> int:
    """Validates that a configuration parameter is a positive integer."""
    if isinstance(value, bool) or not isinstance(value, int) or value < 1:
        raise ValueError(f"{name} must be a positive integer, got {value!r}.")
    return value


class FleetDegradationSimulator:
    """Deterministic Wiener / Random Walk fleet degradation generator.

    Generates bounded sensor telemetry guaranteed to satisfy
    ``TelemetryPayload`` constraints while progressively drifting subsets of
    the fleet toward thermal, power, or strain overload regimes.
    """

    def __init__(
        self,
        num_machines: int = 5,
        shift_hours: int = 12,
        num_shifts: int = 2,
        interval_hours: int = 1,
        seed: int = RANDOM_STATE,
    ) -> None:
        """Initializes the fleet simulator with deterministic RNG state.

        Args:
            num_machines: Number of independent assets in the fleet.
            shift_hours: Duration of one operating shift in hours.
            num_shifts: Number of consecutive shifts to simulate.
            interval_hours: Telemetry sampling interval in hours.
            seed: Deterministic seed for ``np.random.default_rng``.

        Raises:
            ValueError: If any integer schedule parameter is non-positive or
                yields zero total simulation steps.
        """
        self.num_machines: int = _validate_positive_int(num_machines, "num_machines")
        self.shift_hours: int = _validate_positive_int(shift_hours, "shift_hours")
        self.num_shifts: int = _validate_positive_int(num_shifts, "num_shifts")
        self.interval_hours: int = _validate_positive_int(
            interval_hours, "interval_hours"
        )
        self.total_steps: int = (
            self.shift_hours * self.num_shifts
        ) // self.interval_hours
        if self.total_steps < 1:
            raise ValueError(
                "shift_hours * num_shifts must be >= interval_hours to produce "
                "at least 1 simulation step."
            )

        self.seed: int = int(seed)
        self.rng: np.random.Generator = np.random.default_rng(self.seed)
        self.machines: list[MachineState] = self._initialize_fleet()

    def _initialize_fleet(self) -> list[MachineState]:
        """Initializes mixed-criticality machines with nominal baseline state."""
        fleet: list[MachineState] = []
        for idx in range(self.num_machines):
            machine_type: str = MACHINE_TYPES[idx % len(MACHINE_TYPES)]
            machine_id: str = f"SAG-PUMP-{idx + 1:02d}"
            air_temp: float = float(
                np.clip(298.0 + self.rng.normal(0.0, 0.8), AIR_TEMP_MIN, AIR_TEMP_MAX)
            )
            proc_temp: float = float(
                np.clip(
                    air_temp + 10.5 + self.rng.normal(0.0, 0.4),
                    max(PROCESS_TEMP_MIN, air_temp - THERMAL_COHERENCE_MARGIN),
                    PROCESS_TEMP_MAX,
                )
            )
            rpm: float = float(
                np.clip(1540.0 + self.rng.normal(0.0, 40.0), RPM_MIN, RPM_MAX)
            )
            torque: float = float(
                np.clip(40.0 + self.rng.normal(0.0, 3.0), TORQUE_MIN, TORQUE_MAX)
            )
            wear: float = float(
                np.clip(self.rng.uniform(5.0, 45.0), TOOL_WEAR_MIN, TOOL_WEAR_MAX)
            )

            # Assign varied degradation profiles so fleet spans normal to critical zones.
            if idx % 3 == 2 or (self.num_machines > 1 and idx == self.num_machines - 1):
                degradation_rate = float(self.rng.uniform(1.6, 2.4))
            elif idx % 3 == 1:
                degradation_rate = float(self.rng.uniform(0.9, 1.3))
            else:
                degradation_rate = float(self.rng.uniform(0.4, 0.7))

            fleet.append(
                MachineState(
                    machine_id=machine_id,
                    machine_type=machine_type,
                    air_temperature_k=round(air_temp, 3),
                    process_temperature_k=round(proc_temp, 3),
                    rotational_speed_rpm=round(rpm, 3),
                    torque_nm=round(torque, 3),
                    tool_wear_min=round(wear, 3),
                    degradation_rate=degradation_rate,
                )
            )
        return fleet

    def _evaluate_latent_failure(self, state: MachineState) -> int:
        """Evaluates underlying physical failure event for operational cost accounting.

        Note:
            Used solely for operational/economic policy comparison, never for
            statistical model generalization evaluation.
        """
        delta_t: float = float(
            compute_temperature_difference(
                state.process_temperature_k, state.air_temperature_k
            )
        )
        power_kw: float = float(
            compute_mechanical_power(state.torque_nm, state.rotational_speed_rpm)
        )
        strain: float = float(
            compute_strain_index(state.tool_wear_min, state.torque_nm)
        )
        heat_stress: float = float(
            compute_heat_stress_ratio(delta_t, state.rotational_speed_rpm)
        )

        # Composite physical hazard score inspired by AI4I failure regimes (TWF/OSF/HDF/PWF)
        hazard_logit: float = -5.2
        if strain > 10500.0:
            hazard_logit += 2.6 + (strain - 10500.0) / 4000.0
        if state.tool_wear_min > 200.0:
            hazard_logit += 1.8 + (state.tool_wear_min - 200.0) / 60.0
        if delta_t < 8.6 and state.rotational_speed_rpm < 1380.0:
            hazard_logit += 2.4
        if heat_stress > 9.5:
            hazard_logit += 1.4
        if power_kw > 9.0 or power_kw < 3.5:
            hazard_logit += 2.0

        prob_failure: float = float(
            1.0 / (1.0 + np.exp(-np.clip(hazard_logit, -20, 20)))
        )
        return int(self.rng.random() < prob_failure)

    def _step_machine(self, state: MachineState) -> None:
        """Advances a single machine's physical state by one interval step."""
        dt: float = float(self.interval_hours)
        sqrt_dt: float = float(np.sqrt(dt))
        rate: float = state.degradation_rate

        # 1. Monotonic cumulative tool wear in [0.0, 400.0]
        wear_drift: float = 4.2 * rate * dt
        wear_noise: float = float(abs(self.rng.normal(0.0, 1.5 * sqrt_dt)))
        next_wear: float = min(
            TOOL_WEAR_MAX,
            max(
                state.tool_wear_min,
                round(state.tool_wear_min + wear_drift + wear_noise, 3),
            ),
        )

        # 2. Bounded Wiener / Random Walk for air temperature
        air_drift: float = 0.08 * rate * dt
        air_noise: float = float(self.rng.normal(0.0, 0.35 * sqrt_dt))
        next_air: float = round(
            float(
                np.clip(
                    state.air_temperature_k + air_drift + air_noise,
                    AIR_TEMP_MIN,
                    AIR_TEMP_MAX,
                )
            ),
            3,
        )

        # 3. Bounded Wiener / Random Walk for process temperature with thermal coherence
        proc_drift: float = 0.14 * rate * dt
        proc_noise: float = float(self.rng.normal(0.0, 0.45 * sqrt_dt))
        raw_proc: float = state.process_temperature_k + proc_drift + proc_noise
        min_coherent_proc: float = max(
            PROCESS_TEMP_MIN, next_air - THERMAL_COHERENCE_MARGIN
        )
        next_proc: float = round(
            float(np.clip(raw_proc, min_coherent_proc, PROCESS_TEMP_MAX)), 3
        )
        if next_proc < next_air - THERMAL_COHERENCE_MARGIN:
            next_proc = round(
                min(PROCESS_TEMP_MAX, next_air - THERMAL_COHERENCE_MARGIN + 0.001), 3
            )

        # 4. Bounded Wiener / Random Walk for rotational speed (gradual fatigue slowdown)
        rpm_drift: float = -10.0 * rate * dt
        rpm_noise: float = float(self.rng.normal(0.0, 22.0 * sqrt_dt))
        next_rpm: float = round(
            float(
                np.clip(
                    state.rotational_speed_rpm + rpm_drift + rpm_noise,
                    RPM_MIN,
                    RPM_MAX,
                )
            ),
            3,
        )

        # 5. Bounded Wiener / Random Walk for torque (progressive load/friction increase)
        torque_drift: float = 1.4 * rate * dt
        torque_noise: float = float(self.rng.normal(0.0, 2.2 * sqrt_dt))
        next_torque: float = round(
            float(
                np.clip(
                    state.torque_nm + torque_drift + torque_noise,
                    TORQUE_MIN,
                    TORQUE_MAX,
                )
            ),
            3,
        )

        state.tool_wear_min = next_wear
        state.air_temperature_k = next_air
        state.process_temperature_k = next_proc
        state.rotational_speed_rpm = next_rpm
        state.torque_nm = next_torque

    def generate_trajectories(self) -> list[TelemetryStep]:
        """Generates the complete deterministic sequence of fleet telemetry steps.

        Returns:
            list[TelemetryStep]: Ordered telemetry steps across all shifts and
                machines.
        """
        trajectories: list[TelemetryStep] = []
        for step_idx in range(self.total_steps):
            elapsed_hours: int = step_idx * self.interval_hours
            shift: int = (elapsed_hours // self.shift_hours) + 1
            hour_in_shift: int = (elapsed_hours % self.shift_hours) + 1

            for state in self.machines:
                if step_idx > 0:
                    self._step_machine(state)

                latent_failure: int = self._evaluate_latent_failure(state)
                payload: dict[str, Any] = {
                    "machine_id": state.machine_id,
                    "machine_type": state.machine_type,
                    "air_temperature_k": state.air_temperature_k,
                    "process_temperature_k": state.process_temperature_k,
                    "rotational_speed_rpm": state.rotational_speed_rpm,
                    "torque_nm": state.torque_nm,
                    "tool_wear_min": state.tool_wear_min,
                }
                trajectories.append(
                    TelemetryStep(
                        step=step_idx + 1,
                        shift=shift,
                        hour_in_shift=hour_in_shift,
                        payload=payload,
                        latent_failure=latent_failure,
                    )
                )
        return trajectories


def _request_json(
    url: str,
    method: str = "GET",
    payload: dict[str, Any] | None = None,
    timeout: float = 5.0,
) -> dict[str, Any]:
    """Executes an HTTP JSON request using Python stdlib ``urllib.request``."""
    data: bytes | None = None
    headers: dict[str, str] = {"Accept": "application/json"}
    if payload is not None:
        data = json.dumps(payload).encode("utf-8")
        headers["Content-Type"] = "application/json"

    req = urllib.request.Request(url=url, data=data, headers=headers, method=method)
    hostname: str | None = urllib.parse.urlparse(url).hostname
    try:
        if hostname in {"localhost", "127.0.0.1", "::1"}:
            opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
            cm = opener.open(req, timeout=timeout)
        else:
            cm = urllib.request.urlopen(req, timeout=timeout)
        with cm as response:
            raw_body: str = response.read().decode("utf-8")
            parsed: Any = json.loads(raw_body)
            if not isinstance(parsed, dict):
                raise RuntimeError(
                    f"Expected JSON object from {method} {url}, got {type(parsed).__name__}."
                )
            return parsed
    except urllib.error.HTTPError as exc:
        detail: str = exc.read().decode("utf-8", errors="replace")
        logger.error("HTTP %d error calling %s %s: %s", exc.code, method, url, detail)
        raise RuntimeError(
            f"HTTP {exc.code} error from {method} {url}: {detail}"
        ) from exc
    except urllib.error.URLError as exc:
        logger.error("Connection error calling %s %s: %s", method, url, exc.reason)
        raise RuntimeError(
            f"Failed to connect to {method} {url}: {exc.reason}"
        ) from exc


def fetch_api_thresholds(api_url: str, timeout: float = 5.0) -> dict[str, float]:
    """Queries ``GET /health`` to verify readiness and retrieve active thresholds."""
    health_url: str = f"{api_url.rstrip('/')}/health"
    health_data: dict[str, Any] = _request_json(
        url=health_url, method="GET", timeout=timeout
    )
    if not health_data.get("model_loaded", False):
        raise RuntimeError(
            f"Inference service at {health_url} reports model_loaded=False."
        )

    raw_thresholds: dict[str, Any] = health_data.get("thresholds", {})
    theta_warning: float = float(
        raw_thresholds.get("theta_warning", DEFAULT_THRESHOLD_WARNING)
    )
    theta_critical: float = float(
        raw_thresholds.get("theta_critical", DEFAULT_THRESHOLD_CRITICAL)
    )
    logger.info(
        "Connected to API %s (version=%s, theta_warning=%.4f, theta_critical=%.4f)",
        api_url,
        health_data.get("model_version", "unknown"),
        theta_warning,
        theta_critical,
    )
    return {
        "theta_warning": theta_warning,
        "theta_critical": theta_critical,
    }


def post_prediction(
    api_url: str,
    payload: dict[str, Any],
    timeout: float = 5.0,
) -> dict[str, Any]:
    """Sends a single telemetry payload to ``POST /predict``."""
    predict_url: str = f"{api_url.rstrip('/')}/predict"
    return _request_json(
        url=predict_url,
        method="POST",
        payload=payload,
        timeout=timeout,
    )


def compute_economic_comparison(
    y_true: Sequence[int],
    y_prob: Sequence[float],
    equipment_types: Sequence[str],
    theta_warning: float,
    theta_critical: float,
    seed: int = RANDOM_STATE,
) -> dict[str, Any]:
    """Computes comparative operational costs across three maintenance policies.

    Reuses ``src.montecarlo.evaluate_policy_cost`` and its stochastic LogNormal
    MTTR and criticality cost parameters.
    """
    calibrated_metrics: dict[str, float] = evaluate_policy_cost(
        y_true=y_true,
        y_prob_calibrated=y_prob,
        equipment_type=equipment_types,
        theta_1=theta_warning,
        theta_2=theta_critical,
        random_seed=seed,
    )
    static_05_metrics: dict[str, float] = evaluate_policy_cost(
        y_true=y_true,
        y_prob_calibrated=y_prob,
        equipment_type=equipment_types,
        theta_1=0.5,
        theta_2=0.5,
        random_seed=seed,
    )
    reactive_metrics: dict[str, float] = evaluate_policy_cost(
        y_true=y_true,
        y_prob_calibrated=y_prob,
        equipment_type=equipment_types,
        theta_1=1.01,
        theta_2=1.02,
        random_seed=seed,
    )

    calibrated_usd: float = round(calibrated_metrics["expected_cost"], 2)
    static_05_usd: float = round(static_05_metrics["expected_cost"], 2)
    reactive_usd: float = round(reactive_metrics["expected_cost"], 2)

    return {
        "calibrated_multi_threshold_usd": calibrated_usd,
        "static_threshold_05_usd": static_05_usd,
        "reactive_run_to_failure_usd": reactive_usd,
        "savings_vs_reactive_usd": round(reactive_usd - calibrated_usd, 2),
        "savings_vs_static_05_usd": round(static_05_usd - calibrated_usd, 2),
        "cost_parameters": {
            "cost_fp_mean_usd": COST_FP_MEAN,
            "cost_tp_mean_usd": COST_TP_MEAN,
            "cost_damage_mean_usd": COST_DAMAGE_MEAN,
            "mttr_mean_hours": MTTR_MEAN_HOURS,
            "downtime_hourly_usd": DOWNTIME_HOURLY_USD,
            "criticality_factors": dict(CRITICALITY_FACTORS),
        },
        "policy_details": {
            "calibrated_multi_threshold": calibrated_metrics,
            "static_threshold_05": static_05_metrics,
            "reactive_run_to_failure": reactive_metrics,
        },
    }


def _log_summary_table(report: dict[str, Any]) -> None:
    """Logs a formatted operational and economic summary table via logger.info."""
    shift_summary: dict[str, dict[str, int]] = report["shift_summary"]
    econ: dict[str, Any] = report["economic_comparison"]
    totals: dict[str, int] = report["total_status_counts"]

    lines: list[str] = [
        "=== Fleet Simulation Operational & Economic Summary ===",
        "Shift | NORMAL | INSPECTION_REQUIRED | CRITICAL_INTERVENTION",
        "------+--------+---------------------+----------------------",
    ]
    for shift_key, counts in shift_summary.items():
        lines.append(
            f"{shift_key:>5} | {counts['NORMAL']:>6} | "
            f"{counts['INSPECTION_REQUIRED']:>19} | "
            f"{counts['CRITICAL_INTERVENTION']:>21}"
        )
    lines.extend(
        [
            "------+--------+---------------------+----------------------",
            f"Total | {totals['NORMAL']:>6} | "
            f"{totals['INSPECTION_REQUIRED']:>19} | "
            f"{totals['CRITICAL_INTERVENTION']:>21}",
            f"Work Orders (OTs) Issued: {len(report['work_orders'])}",
            (
                "Policy Costs (USD): "
                f"Calibrated=${econ['calibrated_multi_threshold_usd']:,.2f} | "
                f"Static(0.5)=${econ['static_threshold_05_usd']:,.2f} | "
                f"Reactive=${econ['reactive_run_to_failure_usd']:,.2f}"
            ),
            (
                "Net Savings (USD): "
                f"vs Reactive=${econ['savings_vs_reactive_usd']:,.2f} | "
                f"vs Static(0.5)=${econ['savings_vs_static_05_usd']:,.2f}"
            ),
            "=======================================================",
        ]
    )
    logger.info("\n%s", "\n".join(lines))


def run_simulation(
    api_url: str,
    num_machines: int = 5,
    shift_hours: int = 12,
    num_shifts: int = 2,
    interval_hours: int = 1,
    seed: int = RANDOM_STATE,
    report_path: str | Path = "reports/shift_report.json",
    timeout: float = 5.0,
) -> dict[str, Any]:
    """Executes the end-to-end fleet simulation against the inference API.

    Args:
        api_url: Base URL of the FastAPI inference service.
        num_machines: Number of simulated machines in the fleet.
        shift_hours: Hours per operating shift.
        num_shifts: Total number of shifts to simulate.
        interval_hours: Sampling interval in hours.
        seed: Deterministic RNG seed.
        report_path: Destination JSON path for the shift report.
        timeout: HTTP request timeout in seconds.

    Returns:
        dict[str, Any]: Structured operational and economic simulation report.
    """
    thresholds: dict[str, float] = fetch_api_thresholds(
        api_url=api_url, timeout=timeout
    )
    simulator = FleetDegradationSimulator(
        num_machines=num_machines,
        shift_hours=shift_hours,
        num_shifts=num_shifts,
        interval_hours=interval_hours,
        seed=seed,
    )
    trajectories: list[TelemetryStep] = simulator.generate_trajectories()

    shift_summary: dict[str, dict[str, int]] = {
        f"shift_{shift_idx}": {status_name: 0 for status_name in OPERATIONAL_STATUSES}
        for shift_idx in range(1, num_shifts + 1)
    }
    total_counts: dict[str, int] = {
        status_name: 0 for status_name in OPERATIONAL_STATUSES
    }
    work_orders: list[dict[str, Any]] = []
    y_true: list[int] = []
    y_prob: list[float] = []
    equipment_types: list[str] = []

    for item in trajectories:
        prediction: dict[str, Any] = post_prediction(
            api_url=api_url,
            payload=item.payload,
            timeout=timeout,
        )
        op_status: str = str(prediction["operational_status"])
        risk_score: float = float(prediction["failure_risk_score"])

        shift_key: str = f"shift_{item.shift}"
        shift_summary[shift_key][op_status] = (
            shift_summary[shift_key].get(op_status, 0) + 1
        )
        total_counts[op_status] = total_counts.get(op_status, 0) + 1

        if op_status in ("INSPECTION_REQUIRED", "CRITICAL_INTERVENTION"):
            work_orders.append(
                {
                    "work_order_id": f"OT-{item.shift:02d}-{item.step:03d}-{item.payload['machine_id']}",
                    "shift": item.shift,
                    "step": item.step,
                    "hour_in_shift": item.hour_in_shift,
                    "machine_id": item.payload["machine_id"],
                    "machine_type": item.payload["machine_type"],
                    "operational_status": op_status,
                    "criticality_level": prediction.get("criticality_level", "UNKNOWN"),
                    "failure_risk_score": round(risk_score, 6),
                    "recommended_cbm_action": prediction.get(
                        "recommended_cbm_action", ""
                    ),
                }
            )

        y_true.append(item.latent_failure)
        y_prob.append(risk_score)
        equipment_types.append(str(item.payload["machine_type"]))

    economic_comparison: dict[str, Any] = compute_economic_comparison(
        y_true=y_true,
        y_prob=y_prob,
        equipment_types=equipment_types,
        theta_warning=thresholds["theta_warning"],
        theta_critical=thresholds["theta_critical"],
        seed=seed,
    )

    report: dict[str, Any] = {
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "validation_scope": (
            "Operational and economic simulation only. Statistical generalization "
            "metrics are evaluated strictly on locked real data (UCI AI4I 2020)."
        ),
        "simulation_config": {
            "api_url": api_url,
            "num_machines": num_machines,
            "shift_hours": shift_hours,
            "num_shifts": num_shifts,
            "interval_hours": interval_hours,
            "total_steps_per_machine": simulator.total_steps,
            "total_events": len(trajectories),
            "seed": seed,
            "thresholds": thresholds,
        },
        "shift_summary": shift_summary,
        "total_status_counts": total_counts,
        "work_orders": work_orders,
        "economic_comparison": economic_comparison,
    }

    output_path: Path = Path(report_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(report, indent=2), encoding="utf-8")
    logger.info("Saved fleet simulation report to %s", output_path)
    _log_summary_table(report)
    return report


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    """Parses command-line arguments for the fleet degradation simulator."""
    parser = argparse.ArgumentParser(
        description=(
            "Run deterministic stochastic fleet degradation simulation against "
            "the FleetReliability-AI FastAPI inference service."
        )
    )
    parser.add_argument(
        "--api-url",
        type=str,
        default="http://localhost:9696",
        help="Base URL of the FastAPI inference service (default: http://localhost:9696).",
    )
    parser.add_argument(
        "--num-machines",
        type=int,
        default=5,
        help="Number of industrial machines in the simulated fleet (default: 5).",
    )
    parser.add_argument(
        "--shift-hours",
        type=int,
        default=12,
        help="Duration of each operating shift in hours (default: 12).",
    )
    parser.add_argument(
        "--num-shifts",
        type=int,
        default=2,
        help="Number of operating shifts to simulate (default: 2).",
    )
    parser.add_argument(
        "--interval-hours",
        type=int,
        default=1,
        help="Telemetry reporting interval in hours (default: 1).",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=RANDOM_STATE,
        help="Deterministic random seed for fleet trajectories and cost simulation (default: 42).",
    )
    parser.add_argument(
        "--report-path",
        type=str,
        default="reports/shift_report.json",
        help="Output file path for the JSON shift report (default: reports/shift_report.json).",
    )
    parser.add_argument(
        "--timeout",
        type=float,
        default=5.0,
        help="HTTP request timeout in seconds (default: 5.0).",
    )
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    """CLI entrypoint for executing the fleet degradation simulator."""
    args: argparse.Namespace = parse_args(argv)
    run_simulation(
        api_url=args.api_url,
        num_machines=args.num_machines,
        shift_hours=args.shift_hours,
        num_shifts=args.num_shifts,
        interval_hours=args.interval_hours,
        seed=args.seed,
        report_path=args.report_path,
        timeout=args.timeout,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
